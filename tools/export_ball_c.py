"""export_ball_c.py —— 把 ball_roi.npz 折成纯卷积权重，生成 C 头文件

BN 折叠：w' = w * gamma/sqrt(var+eps)，b' = (b-mean)*scale + beta
输出：build/ball_weights.h（float 数组）
"""
import os

import numpy as np

SRC = r"data/ball_roi_full2/model/ball_roi.npz"
OUT = r"build/ball_weights.h"


def fold(d, ck, bk):
    w = d[ck + ".weight"].astype(np.float32)
    b = d[ck + ".bias"].astype(np.float32)
    g = d[bk + ".weight"].astype(np.float32)
    be = d[bk + ".bias"].astype(np.float32)
    m = d[bk + ".running_mean"].astype(np.float32)
    v = d[bk + ".running_var"].astype(np.float32)
    s = g / np.sqrt(v + 1e-5)
    return (w * s.reshape(-1, 1, 1, 1)).reshape(-1), (b - m) * s + be


def emit(name, arr, fh):
    flat = np.asarray(arr, dtype=np.float32).reshape(-1)
    fh.write("static const float %s[%d] = {\n" % (name, flat.size))
    for i in range(0, flat.size, 8):
        fh.write("  " + ",".join("%.8ff" % x for x in flat[i:i + 8]) + ",\n")
    fh.write("};\n")


def main():
    d = np.load(SRC)
    w1, b1 = fold(d, "f.0", "f.1")
    w2, b2 = fold(d, "f.4", "f.5")
    w3, b3 = fold(d, "f.8", "f.9")
    wh = d["head.weight"].astype(np.float32).reshape(-1)
    bh = d["head.bias"].astype(np.float32).reshape(-1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// auto-generated by export_ball_c.py\n")
        fh.write("#pragma once\n\n")
        emit("W1", w1, fh)   # [16][3][3][3]
        emit("B1", b1, fh)
        emit("W2", w2, fh)   # [32][16][3][3]
        emit("B2", b2, fh)
        emit("W3", w3, fh)   # [64][32][3][3]
        emit("B3", b3, fh)
        emit("WH", wh, fh)   # [64]
        emit("BH", bh, fh)
    print("H_OK", OUT, "floats", w1.size + w2.size + w3.size + wh.size)


if __name__ == "__main__":
    main()